// Regenerates src/generated.ts from the Foundry artifacts so the SDK's contract ABIs always match the deployed code.
// Usage: node scripts/gen-abis.mjs (run `forge build` in contracts/ first).
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const contracts = [
  'BtcMusdOracle',
  'WsMUSD',
  'CollateralBTC',
  'BorrowAccountFactory',
  'BorrowAccount',
  'MusdDispenser',
  'Backstop',
  'FlashLiquidator',
  'FeeRouter',
  'RiskLens',
  'BaserateAllocator',
  'WsMusdLiquidityAdapter',
  // Morpho Vault V2 (vault-v2 tag 2026-08-13), the contract behind vMUSD.
  'VaultV2',
]
const out = new URL('../../../contracts/out/', import.meta.url)

let src = '// Generated by scripts/gen-abis.mjs from contracts/out. Do not edit by hand.\n\n'
for (const name of contracts) {
  const { abi } = JSON.parse(readFileSync(new URL(`${name}.sol/${name}.json`, out), 'utf8'))
  src += `export const ${name[0].toLowerCase()}${name.slice(1)}Generated = ${JSON.stringify(abi, null, 2)} as const\n\n`
}
const target = fileURLToPath(new URL('../src/generated.ts', import.meta.url))
writeFileSync(target, src)
// Format with the repo's Biome config so the generated file passes `pnpm lint` as written.
execFileSync('pnpm', ['exec', 'biome', 'format', '--write', target], { stdio: 'inherit' })
console.log(`wrote src/generated.ts (${contracts.length} contracts)`)
