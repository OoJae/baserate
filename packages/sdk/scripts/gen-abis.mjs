// Regenerates src/generated.ts from the Foundry artifacts so the SDK's contract ABIs always match the deployed code.
// Usage: node scripts/gen-abis.mjs (run `forge build` in contracts/ first).
import { readFileSync, writeFileSync } from 'node:fs'

const contracts = ['BtcMusdOracle', 'WsMUSD', 'CollateralBTC', 'BorrowAccountFactory', 'BorrowAccount', 'MusdDispenser']
const out = new URL('../../../contracts/out/', import.meta.url)

let src = '// Generated by scripts/gen-abis.mjs from contracts/out. Do not edit by hand.\n\n'
for (const name of contracts) {
  const { abi } = JSON.parse(readFileSync(new URL(`${name}.sol/${name}.json`, out), 'utf8'))
  src += `export const ${name[0].toLowerCase()}${name.slice(1)}Generated = ${JSON.stringify(abi, null, 2)} as const\n\n`
}
writeFileSync(new URL('../src/generated.ts', import.meta.url), src)
console.log(`wrote src/generated.ts (${contracts.length} contracts)`)
